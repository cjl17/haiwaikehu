#!/bin/bash
# 关闭pwm触发, 关闭08bc相机
echo 50000000 > /sys/class/pwm/pwmchip3/pwm0/duty_cycle
echo 0 > /sys/class/pwm/pwmchip3/pwm0/enable
i2ctransfer -y -f 2 w3@0x34 0x02 0xd3 0x00
i2ctransfer -y -f 2 w3@0x34 0x02 0xd6 0x00
i2ctransfer -y -f 2 w3@0x34 0x02 0xbe 0x00
i2ctransfer -y -f 2 w3@0x34 0x02 0xbe 0x10
i2ctransfer -y -f 2 w3@0x34 0x02 0xd3 0x84
i2ctransfer -y -f 2 w3@0x34 0x02 0xd6 0x84
